from __future__ import annotations

import hashlib
from copy import deepcopy
from typing import Any


def _source(
    key: str,
    label: str,
    summary: str,
    *facts: str,
    status: str = "verified",
    authority: str = "system_of_record",
    max_age_seconds: int = 2_592_000,
) -> dict[str, Any]:
    evidence_hash = hashlib.sha256(
        "|".join((key, label, summary, *facts)).encode("utf-8")
    ).hexdigest()
    return {
        "key": key,
        "label": label,
        "status": status,
        "summary": summary,
        "facts": list(facts),
        "authority": authority,
        "integrity": "sha256_verified",
        "integrity_hash": evidence_hash,
        "observed_at": "2026-08-16T18:00:00Z",
        "max_age_seconds": max_age_seconds,
        "conflicts": [],
    }


def _case(
    *,
    case_id: str,
    customer_id: str,
    customer: str,
    title: str,
    task_type: str,
    request: str,
    amount: float,
    expected_mode: str,
    permission_floor: str,
    priority: str,
    queue_status: str,
    customer_goal: str,
    business_guardrail: str,
    sources: list[dict[str, Any]],
    options: list[dict[str, Any]],
    reason: str,
    lesson: str,
    account_type: str = "standard",
    region: str = "US",
    contract_type: str = "retail_standard",
    fraud_signal: bool = False,
    safety_critical: bool = False,
    auto_cost_cap: float = 150.0,
    events: list[dict[str, Any]] | None = None,
    customer_segment: str = "consumer",
) -> dict[str, Any]:
    evidence_as_of = "2026-08-16T20:00:00Z"
    sourced_records = deepcopy(sources)
    for source in sourced_records:
        source["source_record_id"] = f"EV-{case_id}-{source['key']}"
        source["source_system"] = str(source["label"]).lower().replace(" ", "_")
        source["correlation"] = {
            "case_id": case_id,
            "customer_id": customer_id,
            "task_type": task_type,
        }
    required_sources = [source["key"] for source in sourced_records]
    prepared_options = deepcopy(options)
    for index, option in enumerate(prepared_options):
        action = str(option.get("action") or "deny")
        option.setdefault(
            "amount",
            _default_action_amount(
                action,
                float(option.get("customer_value", 0)),
                float(option.get("company_cost", 0)),
            ),
        )
        option.setdefault("goal_fit", 1.0)
        option.setdefault("eligible", True)
        option.setdefault("permission_floor", permission_floor)
        option.setdefault("auto_cost_cap", auto_cost_cap)
        option.setdefault("safety_critical", safety_critical)
        option.setdefault(
            "value_components",
            [
                {
                    "label": "Resolved customer value",
                    "amount": option.get("customer_value", 0),
                    "basis": "Case economics source",
                }
            ],
        )
        if index == 0:
            option.setdefault("reason", reason)
            option.setdefault("lesson", lesson)
    return {
        "case_id": case_id,
        "title": title,
        "queue_status": queue_status,
        "priority": priority,
        "customer": {
            "customer_id": customer_id,
            "display_name": customer,
            "account_type": account_type,
            "region": region,
            "contract_type": contract_type,
        },
        "task_type": task_type,
        "request_text": request,
        "requested_amount": amount,
        "existing_credit": 0.0,
        "fraud_signal": fraud_signal,
        "ground_truth_amount": prepared_options[0]["amount"],
        "expected_mode": expected_mode,
        "customer_segment": customer_segment,
        "evidence_as_of": evidence_as_of,
        "customer_goal": customer_goal,
        "business_guardrail": business_guardrail,
        "evidence_required": required_sources,
        "evidence_sources": sourced_records,
        "resolution_options": prepared_options,
        "resolution_constraints": {
            "default_permission_floor": permission_floor,
            "auto_cost_cap": auto_cost_cap,
            "safety_critical": safety_critical,
            "resolution_cost_cap": max(float(amount), float(auto_cost_cap)),
            "minimum_goal_fit": 0.0,
        },
        "events": events or [],
        "payments": [],
    }


def _default_action_amount(action: str, customer_value: float, company_cost: float) -> float:
    if action in {
        "deny",
        "guided_troubleshooting",
        "cost_containment",
        "rollback_deployment",
        "least_privilege_fix",
        "database_capacity_recovery",
        "traffic_stabilization",
        "security_containment",
        "isolated_restore",
        "quota_adjustment",
    }:
        return 0.0
    if action in {"partial_refund", "refund"}:
        return company_cost
    return customer_value


