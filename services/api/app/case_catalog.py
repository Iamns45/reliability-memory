def analyst_case_records() -> list[dict[str, Any]]:
    return deepcopy(list(ANALYST_CASES))


def analyst_case_record(case_id: str) -> dict[str, Any] | None:
    return next((record for record in analyst_case_records() if record["case_id"] == case_id), None)


def customer_context(customer_id: str) -> dict[str, Any]:
    record = next(
        (item for item in ANALYST_CASES if item["customer"]["customer_id"] == customer_id),
        None,
    )
    if record is None:
        return {
            "customer": {
                "customer_id": customer_id,
                "display_name": "Unassigned customer",
                "account_type": "standard",
                "region": "US",
                "contract_type": "retail_standard",
            },
            "events": [],
            "payments": [],
            "case_evidence": {},
        }
    return {
        "customer": deepcopy(record["customer"]),
        "events": deepcopy(record["events"]),
        "payments": deepcopy(record["payments"]),
        "case_evidence": {
            "issue_type": record["task_type"],
            "customer_segment": record["customer_segment"],
            "evidence_as_of": record["evidence_as_of"],
            "customer_goal": record["customer_goal"],
            "business_guardrail": record["business_guardrail"],
            "evidence_required": deepcopy(record["evidence_required"]),
            "evidence_sources": deepcopy(record["evidence_sources"]),
            "resolution_options": deepcopy(record["resolution_options"]),
            "resolution_constraints": deepcopy(record["resolution_constraints"]),
        },
    }
